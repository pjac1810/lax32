"""LAX-32's demo song -> src/demo.h: an original piece in A minor (Am F C G), 25 bars at 104 BPM, on the module's
eight parts and its rhythm part. Events: (delta ticks at 96 a beat, part << 4 | kind, d1, d2); kinds: 0 note on,
1 note off, 2 program, 3 controller.

  python3 tools/gen_demo.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "demo.h"
Q = 96
E = Q // 2  # an eighth
BAR = 4 * Q
ev = []  # (tick, order, part, kind, d1, d2)


def note(part, t, n, dur, vel=100):
  ev.append((t, 1, part, 0, n, vel))
  ev.append((t + dur - 4, 0, part, 1, n, 0))


def setup():
  progs = {0: 0, 1: 64, 2: 48, 3: 95, 4: 72, 5: 97, 6: 32, 7: 26}
  vols = {0: 92, 1: 104, 2: 72, 3: 84, 4: 100, 5: 82, 6: 64, 7: 80, 8: 100}
  pans = {0: 50, 1: 64, 2: 82, 3: 46, 4: 72, 5: 92, 6: 30, 7: 64, 8: 64}
  for p, g in progs.items():
    ev.append((0, -1, p, 2, g, 0))
  for p in range(9):
    ev.append((0, -1, p, 3, 7, vols[p]))
    ev.append((0, -1, p, 3, 10, pans[p]))


CH = {"Am": [57, 60, 64], "F": [53, 57, 60], "C": [55, 60, 64], "G": [55, 59, 62]}
ROOT = {"Am": 45, "F": 41, "C": 48, "G": 43}
PROG = ["Am", "F", "C", "G"]
MELODY = [  # (note, eighths) per bar; 0 = rest
  [(76, 2), (81, 2), (79, 1), (76, 1), (74, 2)], [(72, 3), (69, 1), (72, 2), (74, 2)], [(76, 2), (79, 2), (76, 2), (72, 2)],
  [(74, 4), (71, 2), (67, 2)], [(69, 2), (72, 2), (76, 2), (81, 2)], [(79, 2), (77, 2), (76, 2), (72, 2)],
  [(74, 2), (76, 2), (79, 3), (76, 1)], [(74, 6), (0, 2)],
]
MELODY2 = MELODY[:7] + [[(71, 2), (74, 2), (69, 4)]]


def main():
  setup()
  for bar in range(25):
    t0 = bar * BAR
    ch = PROG[bar % 4] if bar < 24 else "Am"
    last = bar == 24
    # bass
    if last:
      note(1, t0, ROOT[ch], BAR)
    else:
      note(1, t0, ROOT[ch], Q + E, 110)
      note(1, t0 + Q + E, ROOT[ch] + 12, E, 90)
      note(1, t0 + 2 * Q, ROOT[ch] + 7, Q, 100)
      note(1, t0 + 3 * Q, ROOT[ch], Q, 96)
    # vibes: arpeggio in the intro
    if bar < 8:
      arp = CH[ch] + [CH[ch][0] + 12]
      for i in range(8):
        note(5, t0 + i * E, arp[[0, 1, 2, 3, 2, 1, 2, 3][i]] + 12, E, 80 if i % 2 else 96)
    # piano and strings from bar 5
    if bar >= 4:
      if last:
        for n in CH[ch]:
          note(0, t0, n, BAR, 96)
      else:
        for at, d in ((0, Q), (Q + E, E), (2 * Q + E, Q + E)):
          for n in CH[ch]:
            note(0, t0 + at, n, d, 88)
      for n in CH[ch]:
        note(2, t0, n + 12, BAR, 70)
    # melody bars 9-24
    if 8 <= bar < 24:
      m = (MELODY if bar < 16 else MELODY2)[(bar - 8) % 8]
      t = t0
      for n, d in m:
        if n:
          note(4, t, n, d * E, 100)
        t += d * E
    # brass stabs, bars 17-24, and the last chord
    if 16 <= bar < 24 and bar % 2 == 1:
      for n in CH[ch]:
        note(3, t0 + 3 * Q + E, n, E, 104)
    if last:
      for n in CH[ch]:
        note(3, t0, n, BAR, 100)
        note(6, t0, n + 12, BAR, 80)
    # drums (the rhythm part is part 8): from bar 3
    if bar >= 2:
      if bar in (8, 16, 24):
        note(8, t0, 49, Q)
      if last:
        note(8, t0, 36, Q)
        continue
      full = bar >= 8
      for b in range(4):
        if b in (0, 2) or (full and b == 2):
          note(8, t0 + b * Q, 36, E, 110)
        if full and b in (1, 3):
          note(8, t0 + b * Q, 38, E, 100)
        if full and b == 3 and bar % 4 == 3:
          note(8, t0 + b * Q + E, 36, E, 90)
      for i in range(8):
        note(8, t0 + i * E, 46 if (full and i == 7 and bar % 8 == 7) else 42, E, 90 if i % 2 == 0 else 64)
      if bar == 23:  # a fill
        for i, n in enumerate((50, 48, 47, 45)):
          note(8, t0 + 3 * Q + i * Q // 4, n, Q // 4, 100)
  ev.sort(key=lambda e: (e[0], e[1]))
  rows, prev = [], 0
  for t, _, part, kind, d1, d2 in ev:
    rows.append((t - prev, part << 4 | kind, d1, d2))
    prev = t
  L = ["/* SPDX-License-Identifier: GPL-3.0-only */", "/* Generated by tools/gen_demo.py (do not edit) */", "#define DEMO_BPM 104",
       f"#define DEMO_N {len(rows)}", "static const struct { uint16_t dt; uint8_t pk, d1, d2; } DEMO[DEMO_N] = {"]
  for i in range(0, len(rows), 6):
    L.append("    " + " ".join(f"{{{a}, {b}, {c}, {d}}}," for a, b, c, d in rows[i:i + 6]))
  L.append("};")
  OUT.write_text("\n".join(L) + "\n")
  print(f"{OUT}: {len(rows)} events, {ev[-1][0] / Q * 60 / 104:.0f} s")


if __name__ == "__main__":
  main()
